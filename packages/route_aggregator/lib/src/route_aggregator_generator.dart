import 'dart:async';

import 'package:analyzer/dart/constant/value.dart';
import 'package:analyzer/dart/element/element.dart';
import 'package:analyzer/dart/element/type.dart';
import 'package:build/build.dart';
import 'package:glob/glob.dart';
import 'package:source_gen/source_gen.dart';

const String defaultRouteAnnotationUrl = 'package:app_core/app/presentation/routes/app_route_annotation.dart#AppRoute';
const String defaultScreenGlobPattern = 'lib/app/presentation/screens/**.dart';

class RouteAggregator {
  RouteAggregator({
    String routeAnnotationUrl = defaultRouteAnnotationUrl,
    String screenGlobPattern = defaultScreenGlobPattern,
  }) : _routeChecker = TypeChecker.fromUrl(routeAnnotationUrl),
       _screenGlob = Glob(screenGlobPattern);

  final TypeChecker _routeChecker;
  final Glob _screenGlob;

  Future<String?> generate(BuildStep buildStep) async {
    final routes = await _RouteCollector(buildStep, _screenGlob, _routeChecker).collect();
    if (routes.isEmpty) {
      return null;
    }

    return _RouteEmitter(routes).emit();
  }
}

class _RouteCollector {
  _RouteCollector(this._buildStep, this._glob, this._routeChecker);

  final BuildStep _buildStep;
  final Glob _glob;
  final TypeChecker _routeChecker;

  Future<List<_RouteDescriptor>> collect() async {
    final assets = <AssetId>[];

    await for (final asset in _buildStep.findAssets(_glob)) {
      if (await _buildStep.canRead(asset)) {
        assets.add(asset);
      }
    }

    assets.sort((a, b) => a.path.compareTo(b.path));

    final descriptors = <_RouteDescriptor>[];

    for (final asset in assets) {
      final library = await _buildStep.resolver.libraryFor(asset);
      final reader = LibraryReader(library);

      for (final element in reader.classes) {
        final annotation = _routeChecker.firstAnnotationOf(element);
        if (annotation == null) continue;

        descriptors.add(_RouteAnnotationParser(element, annotation).parse());
      }
    }

    descriptors.sort((a, b) => a.name.compareTo(b.name));

    final names = {for (final route in descriptors) route.name};
    for (final route in descriptors) {
      final parent = route.parentName;
      if (parent != null && !names.contains(parent)) {
        throw InvalidGenerationSourceError(
          'Parent route "$parent" not found for "${route.name}".',
          element: route.element,
        );
      }
    }

    return List.unmodifiable(descriptors);
  }
}

class _RouteAnnotationParser {
  _RouteAnnotationParser(this._element, this._annotation);

  final ClassElement _element;
  final DartObject _annotation;

  _RouteDescriptor parse() {
    if (_element.isAbstract) {
      throw InvalidGenerationSourceError('Route target "${_element.name}" must not be abstract.', element: _element);
    }

    final reader = ConstantReader(_annotation);
    final nameValue = reader.read('name').objectValue;
    final enumName = _EnumValue(nameValue, _element);

    final pathReader = reader.peek('path');
    final path = pathReader == null || pathReader.isNull ? enumName.name : pathReader.stringValue;

    final parentReader = reader.peek('parent');
    final parent = parentReader == null || parentReader.isNull ? null : _EnumValue(parentReader.objectValue, _element);

    final paramsReader = reader.peek('params');
    final className = _element.displayName;

    final params = paramsReader == null || paramsReader.isNull
        ? const <String>[]
        : paramsReader.listValue.map((value) => _readParam(value, _element)).toList();

    return _RouteDescriptor(
      element: _element,
      name: enumName.name,
      routeNameLiteral: enumName.literal,
      path: path,
      parentName: parent?.name,
      parentLiteral: parent?.literal,
      widgetClassName: className,
      params: params,
      useConstConstructor: _hasConstConstructor(_element),
    );
  }

  static String _readParam(DartObject value, Element target) {
    final param = value.toStringValue();
    if (param == null || param.trim().isEmpty) {
      throw InvalidGenerationSourceError('Route parameters must be non-empty string literals.', element: target);
    }
    return param;
  }

  static bool _hasConstConstructor(ClassElement element) {
    return element.constructors.any((ctor) => ctor.isConst && !ctor.isFactory);
  }
}

class _RouteEmitter {
  _RouteEmitter(this._routes);

  final List<_RouteDescriptor> _routes;

  String emit() {
    final buffer = StringBuffer();
    final children = _buildChildrenMap();
    final ordered = _hierarchyOrder(children);

    // Generate imports
    buffer.writeln('// GENERATED CODE - DO NOT MODIFY BY HAND');
    buffer.writeln('// Generated by route_aggregator');
    buffer.writeln();
    buffer.writeln("import 'package:app_core/app/presentation/routes/route_name.dart';");
    buffer.writeln("import 'package:app_core/app/presentation/routes/route_registry.dart';");

    // Import all screen classes
    final screenImports = _routes.map((r) => r.element.library.identifier).toSet().toList()..sort();
    for (final import in screenImports) {
      buffer.writeln("import '$import';");
    }
    buffer.writeln("import 'package:freezed_annotation/freezed_annotation.dart';");

    buffer.writeln();
    buffer.writeln("part '../../../generated/app/presentation/routes/app_routes.freezed.dart';");
    buffer.writeln();

    _writeSealedClass(buffer);
    _writeRouteRegistry(buffer, ordered);

    return buffer.toString();
  }

  void _writeSealedClass(StringBuffer buffer) {
    buffer.writeln('@freezed');
    buffer.writeln(r'sealed class AppRoute with _$AppRoute {');
    for (final route in _routes) {
      buffer.writeln('  const factory AppRoute.${route.factoryName}() = ${route.routeClassName};');
    }

    buffer.writeln();
    buffer.writeln('  const AppRoute._();');
    buffer.writeln();
    buffer.writeln('  String get name => switch (this) {');
    for (final route in _routes) {
      buffer.writeln('    ${route.routeClassName}() => ${route.routeNameLiteral}.name,');
    }
    buffer.writeln('  };');
    buffer.writeln('}');
    buffer.writeln();
  }

  void _writeRouteRegistry(StringBuffer buffer, List<_RouteDescriptor> ordered) {
    buffer.writeln('final routeRegistry = RouteRegistry([');
    for (var i = 0; i < ordered.length; i++) {
      final route = ordered[i];
      final isLast = i == ordered.length - 1;
      buffer.writeln('  RouteInfo(');
      buffer.writeln('    name: ${route.routeNameLiteral}.name,');
      buffer.writeln('    path: ${_stringLiteral(route.path)},');
      if (route.parentLiteral != null) {
        buffer.writeln('    parent: ${route.parentLiteral}.name,');
      }
      buffer.writeln('    builder: (context, state) => ${_buildConstructor(route)},');
      buffer.writeln('  )${isLast ? '' : ','}');
    }
    buffer.writeln(']);');
  }

  Map<String, List<_RouteDescriptor>> _buildChildrenMap() {
    final map = <String, List<_RouteDescriptor>>{};
    for (final route in _routes) {
      final parent = route.parentName;
      if (parent == null) continue;
      map.putIfAbsent(parent, () => <_RouteDescriptor>[]).add(route);
    }
    for (final list in map.values) {
      list.sort((a, b) => a.name.compareTo(b.name));
    }
    return map;
  }

  List<_RouteDescriptor> _hierarchyOrder(Map<String, List<_RouteDescriptor>> children) {
    final roots = _routes.where((route) => route.parentName == null).toList()..sort((a, b) => a.name.compareTo(b.name));

    final ordered = <_RouteDescriptor>[];
    final visiting = <String>{};
    final visited = <String>{};

    void traverse(_RouteDescriptor route) {
      if (visiting.contains(route.name)) {
        throw InvalidGenerationSourceError(
          'Circular route hierarchy detected at "${route.name}".',
          element: route.element,
        );
      }
      if (visited.contains(route.name)) return;

      visiting.add(route.name);
      ordered.add(route);

      final next = children[route.name] ?? const <_RouteDescriptor>[];
      for (final child in next) {
        traverse(child);
      }

      visiting.remove(route.name);
      visited.add(route.name);
    }

    for (final root in roots) {
      traverse(root);
    }

    for (final route in _routes) {
      if (!visited.contains(route.name)) {
        traverse(route);
      }
    }

    return ordered;
  }
}

class _RouteDescriptor {
  _RouteDescriptor({
    required this.element,
    required this.name,
    required this.routeNameLiteral,
    required this.path,
    required this.widgetClassName,
    required List<String> params,
    required this.useConstConstructor,
    this.parentName,
    this.parentLiteral,
  }) : params = List.unmodifiable(params);

  final ClassElement element;
  final String name;
  final String routeNameLiteral;
  final String path;
  final String widgetClassName;
  final String? parentName;
  final String? parentLiteral;
  final List<String> params;
  final bool useConstConstructor;

  String get factoryName => _toCamelCase(name);

  String get routeClassName => '${_toPascalCase(name)}Route';
}

class _EnumValue {
  _EnumValue(this._value, this._target) {
    final type = _value.type;
    if (type is! InterfaceType) {
      throw InvalidGenerationSourceError('Expected an enum value.', element: _target);
    }

    final element = type.element;
    if (element is! EnumElement) {
      throw InvalidGenerationSourceError('Expected an enum value.', element: _target);
    }

    final index = _value.getField('index')?.toIntValue();
    if (index == null || index < 0 || index >= element.constants.length) {
      throw InvalidGenerationSourceError('Invalid enum constant.', element: _target);
    }

    final constant = element.constants[index];
    name = constant.displayName;
    literal = '${element.name}.$name';
  }

  final DartObject _value;
  final Element _target;

  late final String name;
  late final String literal;
}

String _buildConstructor(_RouteDescriptor route) {
  if (route.params.isEmpty) {
    final prefix = route.useConstConstructor ? 'const ' : '';
    return '$prefix${route.widgetClassName}()';
  }

  final buffer = StringBuffer('${route.widgetClassName}(');
  for (var index = 0; index < route.params.length; index++) {
    if (index > 0) buffer.write(', ');
    final param = route.params[index];
    final literal = _stringLiteral(param);
    buffer.write(
      '$param: state.pathParameters[$literal] ?? '
      'state.uri.queryParameters[$literal] ?? '
      "(throw ArgumentError('Missing required \"$param\" for route \"${_escapeString(route.name)}\"'))",
    );
  }
  buffer.write(')');
  return buffer.toString();
}

List<String> _splitName(String input) {
  return input.split(RegExp(r'[_\-\s]+')).where((part) => part.isNotEmpty).toList();
}

String _toCamelCase(String input) {
  final parts = _splitName(input);
  if (parts.isEmpty) return input;
  final first = parts.first;
  final rest = parts.skip(1).map(_capitalize).join();
  return first + rest;
}

String _toPascalCase(String input) {
  final parts = _splitName(input);
  if (parts.isEmpty) return _capitalize(input);
  return parts.map(_capitalize).join();
}

String _capitalize(String value) {
  if (value.isEmpty) return value;
  if (value.length == 1) return value.toUpperCase();
  return value[0].toUpperCase() + value.substring(1);
}

String _stringLiteral(String value) {
  return "'${_escapeString(value)}'";
}

String _escapeString(String value) {
  final buffer = StringBuffer();
  for (final codeUnit in value.codeUnits) {
    final char = String.fromCharCode(codeUnit);
    if (char == r'\\' || char == "'" || char == r'$') {
      buffer.write(r'\\');
    }
    buffer.write(char);
  }
  return buffer.toString();
}
